"""Gate nginx ``auth_request`` server body for external dashboard auth."""

from raft.core.core.config.settings.dashboard_config import DashboardConfig
from raft.core.lifecycle.render.acl.proxy_location import AclProxyLocation

from .target import DashboardTarget


class DashboardEdgeAuth:
    """Render the Host server that subrequests ``verifyUrl``."""

    def server(self, cfg: DashboardConfig, *, ssl: bool, acl_include: str) -> str:
        host = str(cfg.public_host).strip()
        listen = "listen 443 ssl;" if ssl else "listen 80;"
        return (
            f"# Generated by raft render — dashboard external auth_request\n"
            "server {\n"
            f"    {listen}\n"
            f"    server_name {host};\n"
            f"{self._ssl_lines(cfg, ssl=ssl)}"
            "    resolver 127.0.0.11 valid=10s ipv6=off;\n\n"
            "    include /etc/nginx/gate/acme_challenge.inc;\n\n"
            f"{self._auth_subrequest(cfg)}"
            f"{self._proxy_location(cfg, acl_include=acl_include)}"
            f"{self._signin_and_offline(cfg, acl_include=acl_include)}"
            "}\n"
        )

    def _auth_subrequest(self, cfg: DashboardConfig) -> str:
        return (
            "    location = /_raft_dashboard_auth {\n"
            "        internal;\n"
            f"        proxy_pass {cfg.auth.verify_url};\n"
            "        proxy_pass_request_body off;\n"
            '        proxy_set_header Content-Length "";\n'
            "        proxy_set_header X-Original-URI $request_uri;\n"
            "        proxy_set_header X-Real-IP $remote_addr;\n"
            "    }\n\n"
        )

    def _proxy_location(self, cfg: DashboardConfig, *, acl_include: str) -> str:
        header = cfg.auth.identity_header
        var = header.lower().replace("-", "_")
        auth = (
            "        auth_request /_raft_dashboard_auth;\n"
            f"        auth_request_set $raft_identity $upstream_http_{var};\n"
            f"        proxy_set_header {header} $raft_identity;\n"
            "        error_page 401 = @raft_dashboard_signin;\n"
        )
        return (
            "    location / {\n"
            f"{acl_include}{auth}"
            f"{self._proxy_pass_body()}"
            "    }\n\n"
        )

    @staticmethod
    def _proxy_pass_body() -> str:
        return (
            "        set $router_upstream http://raft-router:80;\n"
            "        proxy_pass $router_upstream;\n"
            "        proxy_http_version 1.1;\n"
            "        proxy_set_header Host $host;\n"
            "        proxy_set_header X-Real-IP $remote_addr;\n"
            "        proxy_set_header X-Forwarded-For "
            "$proxy_add_x_forwarded_for;\n"
            "        proxy_set_header X-Forwarded-Proto $scheme;\n"
            "        proxy_connect_timeout 3s;\n"
            "        proxy_read_timeout 60s;\n"
            "        proxy_intercept_errors on;\n"
            "        error_page 502 503 504 /offline.html;\n"
        )

    def _signin_and_offline(self, cfg: DashboardConfig, *, acl_include: str) -> str:
        return (
            "    location @raft_dashboard_signin {\n"
            f"        return 302 {cfg.auth.sign_in_url};\n"
            "    }\n\n"
            + AclProxyLocation.offline_and_forbidden(acl_include=acl_include)
        )

    @staticmethod
    def _ssl_lines(cfg: DashboardConfig, *, ssl: bool) -> str:
        if not ssl:
            return ""
        stem = "acme" if cfg.tls == "acme" else "origin"
        name = DashboardTarget.SERVICE_NAME
        return (
            f"    ssl_certificate     /etc/nginx/certs/{name}/{stem}.pem;\n"
            f"    ssl_certificate_key /etc/nginx/certs/{name}/{stem}.key;\n\n"
        )
