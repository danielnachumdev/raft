"""Write compiled firewall nginx includes under ``gate-http/firewall/``."""

from pathlib import Path

from raft.core.core.models.app import App
from raft.core.core.models.firewall import SERVICE_ANY
from .compiler import CompiledFragment, FirewallCompiler, scope_name
from .effective import FirewallEffective


class FirewallIncWriter:
    """Persist compiled fragments; expose include lines for gate Host servers."""

    def __init__(
        self,
        gate_http_dir: Path,
        effective: FirewallEffective,
        *,
        ports: tuple[int, ...],
    ) -> None:
        self._dir = gate_http_dir / "firewall"
        self._effective = effective
        self._ports = ports if ports else (80,)
        self._compiler = FirewallCompiler()
        self._fragments: dict[str, CompiledFragment] = {}

    def write_all(self, apps: list[App]) -> None:
        self._dir.mkdir(parents=True, exist_ok=True)
        self._fragments.clear()
        services = self._services(apps)
        keep: set[str] = set()
        for port in self._ports:
            for service in services:
                keep.add(self._write_scope(service, port))
        self._prune(keep)
        self._write_maps()

    def _services(self, apps: list[App]) -> list[str]:
        names = {SERVICE_ANY}
        for app in apps:
            names.add(app.name)
        for rule in self._effective.document.rules:
            svc = rule.service.strip() or SERVICE_ANY
            names.add(svc)
        return sorted(names)

    def clear_all(self) -> None:
        """Remove firewall includes/maps when ACL v1 still owns render."""
        if self._dir.is_dir():
            for path in self._dir.glob("*.inc"):
                path.unlink()
        maps = self._dir.parent / "firewall-maps.conf"
        if maps.is_file():
            maps.unlink()
        self._fragments.clear()

    def gate_include(self, port: int) -> str:
        return self._include_line(scope_name(service=SERVICE_ANY, port=port))

    def host_include(self, app_name: str, port: int) -> str:
        """One fragment: ``any`` + this App, preserving global rule order."""
        return self._include_line(scope_name(service=app_name, port=port))

    def maps_conf(self) -> str:
        parts = ["# Generated by raft render — firewall drop maps\n"]
        for fragment in self._fragments.values():
            text = self._compiler.geo_map_text(fragment)
            if text:
                parts.append(text)
        if len(parts) == 1:
            return ""
        return "".join(parts)

    def needs_forbidden(self, *, service: str, port: int) -> bool:
        fragment = self._fragments.get(scope_name(service=service, port=port))
        return bool(fragment and fragment.access)

    def _write_scope(self, service: str, port: int) -> str:
        scope = scope_name(service=service, port=port)
        fragment = self._compiler.compile_for(
            self._effective.document.rules,
            port=port,
            service=service,
            scope=scope,
        )
        self._fragments[scope] = fragment
        rel = f"{scope}.inc"
        body = self._compiler.location_text(fragment) if fragment.is_active() else ""
        (self._dir / rel).write_text(body, encoding="utf-8")
        return rel

    def _include_line(self, scope: str) -> str:
        fragment = self._fragments.get(scope)
        if fragment is not None:
            if not fragment.is_active():
                return ""
        else:
            path = self._dir / f"{scope}.inc"
            if not path.is_file() or path.stat().st_size == 0:
                return ""
        return f"        include /etc/nginx/http-generated/firewall/{scope}.inc;\n"

    def _write_maps(self) -> None:
        text = self.maps_conf()
        path = self._dir.parent / "firewall-maps.conf"
        if text:
            path.write_text(text, encoding="utf-8")
        elif path.is_file():
            path.unlink()

    def _prune(self, keep: set[str]) -> None:
        for path in self._dir.glob("*.inc"):
            if path.name not in keep:
                path.unlink()
