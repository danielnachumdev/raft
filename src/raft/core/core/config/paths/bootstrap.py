"""Create data-home directories and sync product templates."""

from pathlib import Path
from typing import Optional

from raft.core.platform.secrets import AppSecretsLayout
from .constants import DATA_DIR_RELS, GENERATED_DIRNAME
from .home import RaftHome
from .package_root import PackageRootFinder
from .templates import ProductTemplateSync


class RaftHomeBootstrap:
    """Ensure ``~/.raft`` layout exists and product templates are synced."""

    def __init__(self) -> None:
        self._home = RaftHome()
        self._finder = PackageRootFinder()
        self._templates = ProductTemplateSync()

    def ensure(
        self,
        home: Optional[Path] = None,
        *,
        package_root: Optional[Path] = None,
    ) -> Path:
        root = home if home is not None else self._home.resolve()
        root.mkdir(parents=True, exist_ok=True)
        self._ensure_data_dirs(root)
        pkg = package_root if package_root is not None else self._finder.find()
        self._templates.sync(root, pkg)
        self._ensure_compose_stubs(root)
        return root

    def _ensure_data_dirs(self, root: Path) -> None:
        for rel in DATA_DIR_RELS:
            (root / rel).mkdir(parents=True, exist_ok=True)
        AppSecretsLayout(root).ensure_root()

    def _ensure_compose_stubs(self, root: Path) -> None:
        stub = root / GENERATED_DIRNAME / "compose.apps.yaml"
        if not stub.is_file():
            stub.write_text(
                "# Generated by `raft render` — do not edit.\nservices: {}\n",
                encoding="utf-8",
            )
        edge_stub = root / GENERATED_DIRNAME / "compose.edge.yaml"
        if not edge_stub.is_file():
            edge_stub.write_text(
                "# Generated by `raft render` — gate published ports from settings edge:\n"
                "services:\n"
                "  raft-gate:\n"
                "    ports:\n"
                '      - "80:80"\n'
                '      - "443:443"\n',
                encoding="utf-8",
            )
