"""Write rendered Compose + nginx artifacts under ``generated/``."""

import logging
from pathlib import Path
from typing import Optional

from raft.core.core.config.paths import GENERATED_DIRNAME
from raft.core.core.config.settings.types import EdgeConfig
from raft.core.core.models.manifest import AppSpec
from raft.core.core.models.stack import Stack
from .acl.proxy_location import AclProxyLocation
from .compose_apps import ComposeAppsYaml
from .edge.fragments import EdgeFragments
from .firewall.policy_includes import PolicyIncludes

logger = logging.getLogger(__name__)


class GeneratedWriter:
    """Persist one render pass's fragments to disk under ``generated/``."""

    def __init__(self, stack: Stack, edge: EdgeConfig) -> None:
        self._stack = stack
        self._edge = edge
        self._root = stack.root / GENERATED_DIRNAME
        gate_http = self._root / "nginx" / "gate-http"
        self._policy = PolicyIncludes(stack.root, edge, gate_http)

    def write_all(
        self, resolved: dict[str, AppSpec], fragments: EdgeFragments
    ) -> None:
        apps_path = self._root / "compose.apps.yaml"
        apps_path.write_text(
            ComposeAppsYaml(self._stack).build(resolved, fragments), encoding="utf-8"
        )
        (self._root / "compose.edge.yaml").write_text(
            self._compose_edge_yaml(), encoding="utf-8"
        )
        hosts = self._root / "nginx" / "router" / "hosts.conf"
        hosts.write_text(self._router_hosts_conf(fragments), encoding="utf-8")
        self._write_gate_http(fragments)
        self._write_gate_stream(fragments)
        self._write_gate_tls(fragments)
        self._write_upstreams(fragments)

    def _compose_edge_yaml(self) -> str:
        lines = [
            "# Generated by `raft render` — gate published ports from settings edge:",
            "services:",
            f"  {self._stack.gate}:",
            "    ports:",
        ]
        published = self._edge.published_ports()
        if not published:
            lines.append("      []")
        else:
            for port, protocol in published:
                if protocol == "tcp":
                    lines.append(f'      - "{port}:{port}"')
                else:
                    lines.append(f'      - "{port}:{port}/{protocol}"')
        lines.append("")
        return "\n".join(lines)

    @staticmethod
    def _router_hosts_conf(fragments: EdgeFragments) -> str:
        blocks: list[str] = [
            "# Generated by `raft render` — do not edit.",
            "",
        ]
        blocks.extend(fragments.router_includes)
        if fragments.router_includes:
            blocks.append("")
        blocks.extend(fragments.router_servers)
        return "\n".join(blocks)

    def _write_gate_http(self, fragments: EdgeFragments) -> None:
        directory = self._root / "nginx" / "gate-http"
        parts: list[str] = ["# Generated by raft render — gate http listeners\n"]
        parts.extend(fragments.gate_http)
        if fragments.gate_http:
            parts.append("\n")
        parts.extend(self._gate_http_servers())
        (directory / "listeners.conf").write_text("".join(parts), encoding="utf-8")
        keep = {"listeners.conf"}
        if (directory / "firewall-maps.conf").is_file():
            keep.add("firewall-maps.conf")
        self._prune_conf_dir(directory, keep=keep, label="gate-http")

    def _gate_http_servers(self) -> list[str]:
        parts: list[str] = []
        if self._edge.http is not None:
            parts.append(self._default_http_server())
        if self._edge.https is not None:
            parts.append(self._default_https_server())
        return parts

    def _default_http_server(self) -> str:
        assert self._edge.http is not None
        acl = self._policy.gate_include(self._edge.http)
        head = (
            "server {\n"
            f"    listen {self._edge.http} default_server;\n"
            "    server_name _;\n"
        )
        if not acl:
            return head + "\n    include /etc/nginx/gate/proxy_router.inc;\n}\n"
        return (
            head
            + "    resolver 127.0.0.11 valid=10s ipv6=off;\n\n"
            + "    include /etc/nginx/gate/acme_challenge.inc;\n\n"
            + AclProxyLocation.location_slash(acl_include=acl)
            + "\n"
            + AclProxyLocation.offline_and_forbidden(acl_include=acl)
            + "}\n"
        )

    def _default_https_server(self) -> str:
        return (
            "\n"
            "server {\n"
            f"    listen {self._edge.https} ssl default_server;\n"
            "    server_name _;\n"
            "    ssl_reject_handshake on;\n"
            "}\n"
        )

    def _write_gate_stream(self, fragments: EdgeFragments) -> None:
        directory = self._root / "nginx" / "gate-stream"
        body = "# Generated by raft render — gate stream servers\n\n"
        if fragments.gate_stream:
            body += "\n".join(fragments.gate_stream)
        else:
            body += "# (no stream ports)\n"
        (directory / "streams.conf").write_text(body, encoding="utf-8")
        self._prune_conf_dir(directory, keep={"streams.conf"}, label=None)

    def _write_gate_tls(self, fragments: EdgeFragments) -> None:
        self._write_named_confs(
            self._root / "nginx" / "gate-tls",
            fragments.gate_tls,
            stale_label="generated TLS snippet",
        )

    def _write_upstreams(self, fragments: EdgeFragments) -> None:
        self._write_named_confs(
            self._stack.upstreams_dir,
            fragments.upstreams,
            stale_label="upstream",
        )

    @staticmethod
    def _write_named_confs(
        directory: Path, mapping: dict[str, str], *, stale_label: str
    ) -> None:
        keep = set(mapping)
        for name, content in mapping.items():
            (directory / name).write_text(content, encoding="utf-8")
        for path in directory.glob("*.conf"):
            if path.name not in keep:
                path.unlink()
                logger.info("removed stale %s %s", stale_label, path.name)

    @staticmethod
    def _prune_conf_dir(
        directory: Path, *, keep: set[str], label: Optional[str]
    ) -> None:
        for stale in directory.glob("*.conf"):
            if stale.name in keep:
                continue
            stale.unlink()
            if label:
                logger.info("removed stale %s %s", label, stale.name)
